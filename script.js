// Language mapping based on navigator.language
function getBrowserLanguage() {
  const lang = navigator.language || navigator.userLanguage;
  if (lang.startsWith('zh-TW') || lang.startsWith('zh-HK')) return 'zh-TW';
  if (lang.startsWith('zh')) return 'zh-CN';
  if (lang.startsWith('ja')) return 'ja';
  if (lang.startsWith('ko')) return 'ko';
  return 'en'; // Default fallback
}

// Current language logic
let currentLang = localStorage.getItem('user_lang');
if (!currentLang) {
  currentLang = getBrowserLanguage();
}

function updateLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('user_lang', lang);
  document.documentElement.lang = lang;
  document.getElementById('lang-select').value = lang;

  // Apply translations
  const elements = document.querySelectorAll('[data-i18n]');
  elements.forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (translations[lang] && translations[lang][key]) {
      if (el.hasAttribute('data-i18n-html')) {
        el.innerHTML = translations[lang][key];
      } else {
        el.textContent = translations[lang][key];
      }
    }
  });

  // Toggle content blocks based on language
  document.querySelectorAll('[data-lang-block]').forEach(el => {
    if (el.getAttribute('data-lang-block') === lang) {
      el.style.display = '';
    } else {
      el.style.display = 'none';
    }
  });

  // Adjust fonts for specific languages
  if (lang === 'ja') {
    document.body.style.fontFamily = "'Plus Jakarta Sans', 'Noto Sans JP', sans-serif";
  } else if (lang === 'ko') {
    document.body.style.fontFamily = "'Plus Jakarta Sans', 'Noto Sans KR', sans-serif";
  } else if (lang === 'zh-CN') {
    document.body.style.fontFamily = "'Plus Jakarta Sans', 'Noto Sans SC', sans-serif";
  } else if (lang === 'zh-TW') {
    document.body.style.fontFamily = "'Plus Jakarta Sans', 'Noto Sans TC', sans-serif";
  } else {
    document.body.style.fontFamily = "'Plus Jakarta Sans', sans-serif";
  }
}

// Event listener for language selector
document.addEventListener('DOMContentLoaded', () => {
  const langSelect = document.getElementById('lang-select');
  if (langSelect) {
    langSelect.addEventListener('change', (e) => {
      updateLanguage(e.target.value);
    });
  }
  
  // Initial language setup
  updateLanguage(currentLang);
  
  // Menu toggle logic
  const toggle = document.querySelector('.menu-toggle');
  const nav = document.querySelector('.main-nav');
  if (toggle && nav) {
    toggle.addEventListener('click', () => {
      const open = nav.classList.toggle('open');
      toggle.setAttribute('aria-expanded', open);
    });
    nav.querySelectorAll('a').forEach(link => link.addEventListener('click', () => {
      nav.classList.remove('open');
      toggle.setAttribute('aria-expanded', 'false');
    }));
  }
});
